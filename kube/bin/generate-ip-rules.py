#!/bin/env python3
import subprocess
from dataclasses import dataclass
import sys
import socket
import requests
import json

# This is a list of the individual services outside our network
# which need to be enabled/disabled on a per service basis. Many
# are shared between services.

@dataclass
class AccessRules:
    amazonS3 :bool = False       # db backups, file generation, passport images etc
    govPay :bool = False
    govNotify :bool = False
    flightStatsApi :bool = False # evw only,
    keycloak :bool = False
    ges :bool = False            # rt only.
    amazonSES :bool = False      # old smtp paths, required for password reset emails


# Adjust which pods can access which internet endpoints here.

services = {
    "rt-emailer": AccessRules(govNotify = True, amazonSES = True)
}

# DNS Entries that need to be turned into IP Addresses

GOV_PAY_DNS = "publicapi.payments.service.gov.uk"
GOV_NOTIFY_DNS = "api.notifications.service.gov.uk"
FLIGHT_STATS_DNS = "api.flightstats.com"
KEYCLOAK_DEV_DNS = "sso-dev.notprod.homeoffice.gov.uk"
KEYCLOAK_PROD_DNS = "sso.digital.homeoffice.gov.uk"
AMAZON_SES_DNS = "email-smtp.eu-west-1.amazonaws.com"
GES_ENDPOINTS = [ "216.81.87.71", "216.81.87.66" ]

# For each service we iterate over it and turn the AccessRules() instance into
# a networkpolicy.yaml file in the service's directory. Use this script to apply
# future changes to the file.

def main():

    for (service, accessRules) in services.items():
        template = buildTemplate(service, accessRules)
        writeTemplate(service, template)

    print("finished")

def writeTemplate(service, template):
    f = open(service + "/egress.yaml", "w")
    f.write(template)
    f.close()
    print("written new %s/egress.yaml file" % (service,))

def buildTemplate(service, accessRules):

    template = mainTemplate % (service, service)

    if (accessRules.amazonS3):
        ips = getAmazonIPRanges("S3")
        template += sectionTemplate % ("Amazon S3", ipListToTemplate(ips))

    if (accessRules.amazonSES):
        ips = resolveDNS(AMAZON_SES_DNS)
        template += sectionTemplate % ("Amazon SES", ipListToTemplate(ips))

    if (accessRules.govPay):
        ips = resolveDNS(GOV_PAY_DNS)
        template += sectionTemplate % ("Gov Pay", ipListToTemplate(ips))

    if (accessRules.govNotify):
        ips = resolveDNS(GOV_NOTIFY_DNS)
        template += sectionTemplate % ("Gov Notify", ipListToTemplate(ips))

    if (accessRules.flightStatsApi):
        ips = resolveDNS(FLIGHT_STATS_DNS)
        template += sectionTemplate % ("Flight Stats API", ipListToTemplate(ips))

    if (accessRules.keycloak):
        ips = resolveDNS(KEYCLOAK_DEV_DNS) + resolveDNS(KEYCLOAK_PROD_DNS)
        template += sectionTemplate % ("Keycloak", ipListToTemplate(ips))

    if (accessRules.ges):
        template += sectionTemplate % ("Global Entry US Servers", ipListToTemplate(GES_ENDPOINTS))

    return template

mainTemplate = """---
# This file is automatically generated by bin/generate-ip-rules.py.
# Edit and rerun the script to apply changes.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: egress-%s
spec:
  podSelector:
    matchLabels:
      name: %s
  egress:
  - to: # all traffic inside namespace allowed (kibana, sysdig, cfssl, db access)
    - ipBlock:
        cidr:
          17.0.0.0/16
    - ipBlock:
        cidr:
          10.0.0.0/8
"""

sectionTemplate = """  - to: # %s
%s
"""

def ipListToTemplate(ipList):
    template = ""
    for ip in sorted(ipList):
        if '/' not in ip:
            ip += "/32" # convert to cidr notation

        template += "    - ipBlock:\n        cidr:\n          %s\n" % (ip,)

    return template


def resolveDNS(domainName):
    ips = []

    for result in socket.getaddrinfo(domainName, None, socket.AF_UNSPEC):
        family, _, _, _, sockaddr = result

        if family == socket.AF_INET:
            if sockaddr[0] not in ips:
                ips.append(sockaddr[0])

    return ips

# Amazon S3 IP Addresses do not come from DNS Lookups. Amazon provides a
# JSON file full of network blocks and we download and filter it.

OUR_AMAZON_REGION="eu-west-2"

def getAmazonIPRanges(service):
	cidrs = []

	ipRangeJson = requests.get("https://ip-ranges.amazonaws.com/ip-ranges.json")
	if (ipRangeJson.status_code != 200):
		print("Error looking up Amazon IPs")
		return []
	else:
		jsonObj = json.loads(ipRangeJson.text)
		for prefix in jsonObj['prefixes']:
			if prefix['region'] == OUR_AMAZON_REGION and prefix['service'] == service:
				cidrs.append(prefix['ip_prefix'])

		return cidrs

if __name__=='__main__':
    main()
